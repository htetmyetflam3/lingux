const cliESM = `if (process.argv[1] && import.meta.url === 'file://' + process.argv[1].replace(/\\\\/g, '/')) {
	const p = process.argv.slice(2);
	const cmd = p[0];
	if (cmd === 'list') {
		const r = {};
		for (const [n, v] of Object.entries(m)) r[n] = Object.keys(v);
		console.log(JSON.stringify(r, null, 2));
	} else if (cmd === 'call' && p.length > 1) {
		const [mod, fn] = p[1].split('.');
		const target = mod ? (m[mod] && m[mod][fn]) : m[p[1]];
		if (typeof target !== 'function') { console.error(JSON.stringify({ e: 'Not found: ' + p[1] })); process.exit(1); }
		try { console.log(JSON.stringify({ r: target(p[2] || '') })); }
		catch (err) { console.error(JSON.stringify({ e: err.message })); process.exit(1); }
	} else {
		const [mod, fn] = (cmd || '').split('.');
		const target = mod === cmd ? m[cmd] : (m[mod] && m[mod][fn]);
		if (typeof target === 'function') {
			try { console.log(JSON.stringify({ r: target(p[1] || '') })); }
			catch (err) { console.error(JSON.stringify({ e: err.message })); process.exit(1); }
		} else { console.error(JSON.stringify({ e: 'Unknown: ' + cmd })); process.exit(1); }
	}
}`;

const esmRuntime = `import crypto from 'node:crypto';
import fs from 'node:fs';
globalThis.__fs = fs;

${core}

${esmExports}

${cliESM}
`;

