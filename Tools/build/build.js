// Write outputs — into the map dir, next to the sources.
fs.writeFileSync(path.join(MAP_DIR, 'actual.mjs'), esmRuntime);
console.log(`actual.mjs: ${(Buffer.byteLength(esmRuntime) / 1024).toFixed(2)} KB`);

fs.writeFileSync(path.join(MAP_DIR, 'map-runtime.cjs'), cjsRuntime);
console.log(`map-runtime.cjs: ${(Buffer.byteLength(cjsRuntime) / 1024).toFixed(2)} KB`);

console.log(`Done. Outputs in: ${MAP_DIR}`);
