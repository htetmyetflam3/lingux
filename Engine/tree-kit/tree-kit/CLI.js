#!/usr/bin/env node
// CLI.js — the only entry point. Two commands, nothing else:
//
//   node CLI.js buildstart   build the trees into ./tree (4 map + 3 graph modules)
//   node CLI.js obfuscator   encrypt master.json -> master.json.enc, emit the
//                            external key (master.key.txt) and the loader secure.js
//
// Loads an optional .env next to this file. All paths are anchored here; the
// tree output is hardcoded to ./tree beside this CLI. Node stdlib only.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const MASTER = path.join(HERE, "master.json");
const TREE_DIR = path.join(HERE, "tree");
const ENC_PATH = path.join(HERE, "master.json.enc");
const KEY_PATH = path.join(HERE, "master.key.txt");
const SECURE_PATH = path.join(HERE, "secure.js");

const MAGIC = "MGR1";
const IV_BYTES = 12;
const TAG_BYTES = 16;
const KEY_BYTES = 32;

// Minimal .env loader: KEY=VALUE lines next to this CLI, if present.
function loadEnv() {
  const envPath = path.join(HERE, ".env");
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq === -1) continue;
    const k = t.slice(0, eq).trim();
    if (!(k in process.env)) process.env[k] = t.slice(eq + 1).trim();
  }
}

// ── command 1: tree build ────────────────────────────────────────────────
async function buildStart() {
  fs.mkdirSync(TREE_DIR, { recursive: true });
  const { runBuild, runBuildPos } = await import("./graph/build.js");
  // Same two-phase build the engine runs: syllable trees, then the POS tree
  // keyed on the minted ids (refArray threaded in memory).
  const { refArray } = await runBuild();
  await runBuildPos(TREE_DIR, refArray);
  console.log(`[buildstart] trees written to ${TREE_DIR}`);
  for (const f of fs.readdirSync(TREE_DIR)) console.log("  -", f);
}

// ── command 2: encrypt master.json + external key + loader ───────────────
function seal(key, plain) {
  const iv = crypto.randomBytes(IV_BYTES);
  const cipher = crypto.createCipheriv("aes-256-gcm", key, iv);
  const ct = Buffer.concat([cipher.update(plain), cipher.final()]);
  return Buffer.concat([Buffer.from(MAGIC, "ascii"), iv, cipher.getAuthTag(), ct]);
}

// The loader. Unlike the old design the key is NOT embedded: secure.js reads
// master.key.txt at runtime, so rotating the key never requires regenerating
// or obfuscating the loader.
const SECURE_SOURCE = `// secure.js — GENERATED by CLI.js obfuscator. Do not edit by hand.
// AES-256-GCM loader for master.json.enc. The key lives in master.key.txt
// beside this file (external sidecar), never inside the loader.
// Container: [4-byte magic "MGR1"][12-byte IV][16-byte auth tag][ciphertext]
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const KEY_FILE = path.join(HERE, "master.key.txt");
const MAGIC = "MGR1";
const IV_BYTES = 12;
const TAG_BYTES = 16;

function loadKey() {
  // Resolution: deployment env first (MASTER_JSON_KEY in .env), then the
  // external sidecar master.key.txt beside this loader. The key is never
  // embedded in this file.
  const fromEnv = (process.env.MASTER_JSON_KEY || "").trim();
  if (fromEnv) {
    const k = Buffer.from(fromEnv, "hex");
    if (k.length === 32) return k;
    throw new Error("MASTER_JSON_KEY must be a 32-byte hex key");
  }
  const key = Buffer.from(fs.readFileSync(KEY_FILE, "utf8").trim(), "hex");
  if (key.length !== 32) throw new Error("master.key.txt must hold a 32-byte hex key");
  return key;
}

function decrypt(file) {
  const container = fs.readFileSync(file);
  if (
    container.length < 4 + IV_BYTES + TAG_BYTES ||
    container.subarray(0, 4).toString("ascii") !== MAGIC
  ) {
    throw new Error("invalid .enc container (expected the MGR1 layout): " + file);
  }
  const iv = container.subarray(4, 4 + IV_BYTES);
  const tag = container.subarray(4 + IV_BYTES, 4 + IV_BYTES + TAG_BYTES);
  const ciphertext = container.subarray(4 + IV_BYTES + TAG_BYTES);
  const decipher = crypto.createDecipheriv("aes-256-gcm", loadKey(), iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(ciphertext), decipher.final()]).toString("utf8");
}

export function readSecureText(file) {
  const enc = file.endsWith(".enc") ? file : file + ".enc";
  if (fs.existsSync(enc)) return decrypt(enc);
  return fs.readFileSync(file, "utf8");
}

export function readSecureJson(file) {
  return JSON.parse(readSecureText(file));
}
`;

function obfuscator() {
  if (!fs.existsSync(MASTER)) throw new Error(`master.json not found: ${MASTER}`);
  const data = fs.readFileSync(MASTER);
  JSON.parse(data.toString("utf8")); // fail fast on a non-JSON source

  const key = crypto.randomBytes(KEY_BYTES);
  const keyHex = key.toString("hex");
  fs.writeFileSync(KEY_PATH, keyHex + "\n", "utf8");
  fs.writeFileSync(ENC_PATH, seal(key, data));
  fs.writeFileSync(SECURE_PATH, SECURE_SOURCE, "utf8");

  console.log("[obfuscator] AES-256-GCM (MGR1) outputs:");
  console.log("  key    ->", path.relative(HERE, KEY_PATH), `(${KEY_BYTES}-byte hex, external)`);
  console.log("  sealed ->", path.relative(HERE, ENC_PATH), `${(ENC_PATH && fs.statSync(ENC_PATH).size)} bytes`);
  console.log("  loader ->", path.relative(HERE, SECURE_PATH), "(reads the external key)");
}

// ── dispatch ─────────────────────────────────────────────────────────────
loadEnv();
const command = process.argv[2];
if (command === "buildstart") {
  buildStart().catch((err) => {
    console.error(err);
    process.exit(1);
  });
} else if (command === "obfuscator") {
  try {
    obfuscator();
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
} else {
  console.error("usage:\n  node CLI.js buildstart\n  node CLI.js obfuscator");
  process.exit(2);
}
